/**
 * Lookup order helper: Searches by ID (case-insensitive) and validates matching email (case-insensitive)
 */
export function lookupCustomerOrder(orderId: string, email: string): { order?: CustomerOrder; error?: string } {
  const normalizedId = orderId.trim().toUpperCase();
  const normalizedEmail = email.trim().toLowerCase();

  const foundOrder = MOCK_ORDERS.find((o) => o.id.toUpperCase() === normalizedId);

  if (!foundOrder) {
    return {
      error: `No dispatch record found for Order ID "${orderId.trim()}". Please verify the code or try one of the demo orders below.`,
    };
  }

  // If email was provided, check if it matches
  if (normalizedEmail && foundOrder.customerEmail.toLowerCase() !== normalizedEmail) {
    return {
      error: `The email address "${email.trim()}" does not match the records for ${orderId.trim()}. For this demo order, try using: ${foundOrder.customerEmail}`,
    };
  }

  return { order: foundOrder };
}
